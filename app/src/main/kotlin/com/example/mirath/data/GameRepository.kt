    fun gamesByCategory(category: String?): List<HistoricalGame> {
        if (category.isNullOrBlank() || category == "الكل") return games
        return games.filter { it.category == category }
    }

    fun searchGames(query: String, selectedCategory: String? = null): List<HistoricalGame> {
        val normalizedQuery = normalizeSearchString(query)
        val filteredByCategory = gamesByCategory(selectedCategory)
        if (normalizedQuery.isBlank()) return filteredByCategory

        return filteredByCategory.filter { game ->
            val haystack = listOf(
                game.title,
                game.englishTitle,
                game.arabicTitle,
                game.region,
                game.era,
                game.category,
                game.tags.joinToString(" "),
                game.description
            ).joinToString(" ")

            normalizeSearchString(haystack).contains(normalizedQuery)
        }
    }

    private fun normalizeSearchString(value: String): String {
        val normalized = Normalizer.normalize(value, Normalizer.Form.NFD)
        val withoutMarks = normalized.replace(Regex("[\\p{Mn}&&[^\\u064B-\\u065F\\u0670]]"), "")
        return withoutMarks
            .replace("أ", "ا")
            .replace("إ", "ا")
            .replace("آ", "ا")
            .replace("ؤ", "و")
            .replace("ئ", "ي")
            .replace("ة", "ة")
            .lowercase()
            .replace(Regex("\\s+"), " ")
            .trim()
    }
